import argparse
import json
import os
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path


DEFAULT_SYSTEM_PROMPT = """You are an assistant for an educational histopathology AI project.
Convert model predictions and XAI evidence into concise, human-readable English.
Do not claim to provide a clinical diagnosis. Emphasize that the result is model-generated
decision support and should be reviewed by a qualified pathologist."""


def parse_args():
    parser = argparse.ArgumentParser(
        description="Generate human-readable explanations from ViT XAI outputs using an LLM."
    )
    parser.add_argument(
        "--input",
        default="outputs/vit_small/xai/xai_explanations.json",
        help="Path to xai_explanations.json generated by scripts/xai_vit.py.",
    )
    parser.add_argument(
        "--output",
        default="outputs/vit_small/xai/llm_report",
        help="Directory for LLM explanation outputs.",
    )
    parser.add_argument(
        "--provider",
        default="mock",
        choices=["mock", "openrouter", "groq", "gemini", "huggingface"],
        help="LLM provider. Use mock to test the pipeline without an API key.",
    )
    parser.add_argument(
        "--model",
        default=None,
        help="Provider model name. If omitted, a sensible default is used.",
    )
    parser.add_argument(
        "--max-samples",
        type=int,
        default=8,
        help="Maximum number of XAI samples to explain.",
    )
    parser.add_argument(
        "--timeout",
        type=int,
        default=60,
        help="HTTP timeout in seconds.",
    )
    parser.add_argument(
        "--sleep",
        type=float,
        default=0.5,
        help="Delay between API calls to avoid rate limits.",
    )
    return parser.parse_args()


def read_json(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)


def write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def label_name(value):
    return "cancer" if int(value) == 1 else "normal"


def confidence_band(prob_cancer, threshold):
    margin = abs(float(prob_cancer) - float(threshold))
    if margin < 0.05:
        return "low confidence / close to threshold"
    if margin < 0.2:
        return "moderate confidence"
    return "high confidence"


def build_prompt(sample):
    prob = float(sample["prob_cancer"])
    threshold = float(sample["threshold"])
    pred = label_name(sample["pred_label"])
    true_label = label_name(sample["true_label"])
    band = confidence_band(prob, threshold)
    top_regions = sample["top_attention_regions"]

    return f"""Explain this histopathology patch-level AI result in clear language.

Inputs:
- Sample ID: {sample["id"]}
- Case group from evaluation: {sample["group"]}
- Model: ViT-Small
- Prediction threshold: {threshold:.2f}
- Cancer probability: {prob:.4f}
- Predicted label: {pred}
- Ground-truth label, if available: {true_label}
- Confidence band: {band}
- Attention Rollout top regions: {top_regions}

Please produce:
1. A one-sentence model result.
2. A short explanation of what image regions influenced the prediction.
3. A reliability note, especially if the probability is close to the threshold.
4. A non-diagnostic safety note."""


def mock_explanation(sample):
    prob = float(sample["prob_cancer"])
    threshold = float(sample["threshold"])
    pred = label_name(sample["pred_label"])
    band = confidence_band(prob, threshold)
    top_regions = sample["top_attention_regions"]

    return (
        f"The ViT-Small model predicts this patch as {pred} with a cancer probability "
        f"of {prob:.3f} using a decision threshold of {threshold:.2f}. "
        f"The Attention Rollout evidence indicates that the model mainly focused on "
        f"{top_regions}. The prediction should be interpreted as {band}, because the "
        f"score is compared against the selected threshold rather than a clinical rule. "
        "This is an AI-generated research explanation and is not a standalone clinical diagnosis."
    )


def request_json(url, headers, payload, timeout):
    data = json.dumps(payload).encode("utf-8")
    request = urllib.request.Request(url, data=data, headers=headers, method="POST")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            response_body = response.read().decode("utf-8")
            return json.loads(response_body)
    except urllib.error.HTTPError as exc:
        error_body = exc.read().decode("utf-8", errors="replace")
        raise RuntimeError(f"HTTP {exc.code}: {error_body}") from exc
    except urllib.error.URLError as exc:
        raise RuntimeError(f"Network error: {exc}") from exc


def call_openrouter(prompt, model, timeout):
    api_key = os.environ.get("OPENROUTER_API_KEY")
    if not api_key:
        raise RuntimeError("OPENROUTER_API_KEY is not set.")
    response = request_json(
        "https://openrouter.ai/api/v1/chat/completions",
        {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
            "HTTP-Referer": "https://github.com/FazhanLiu/cancer-cell-classification-pipeline",
            "X-Title": "Cancer Cell Classification Pipeline",
        },
        {
            "model": model or "meta-llama/llama-3.1-8b-instruct:free",
            "messages": [
                {"role": "system", "content": DEFAULT_SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.2,
        },
        timeout,
    )
    return response["choices"][0]["message"]["content"].strip()


def call_groq(prompt, model, timeout):
    api_key = os.environ.get("GROQ_API_KEY")
    if not api_key:
        raise RuntimeError("GROQ_API_KEY is not set.")
    response = request_json(
        "https://api.groq.com/openai/v1/chat/completions",
        {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        {
            "model": model or "llama-3.1-8b-instant",
            "messages": [
                {"role": "system", "content": DEFAULT_SYSTEM_PROMPT},
                {"role": "user", "content": prompt},
            ],
            "temperature": 0.2,
        },
        timeout,
    )
    return response["choices"][0]["message"]["content"].strip()


def call_gemini(prompt, model, timeout):
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        raise RuntimeError("GEMINI_API_KEY is not set.")
    gemini_model = model or "gemini-1.5-flash"
    response = request_json(
        f"https://generativelanguage.googleapis.com/v1beta/models/{gemini_model}:generateContent?key={api_key}",
        {"Content-Type": "application/json"},
        {
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": f"{DEFAULT_SYSTEM_PROMPT}\n\n{prompt}"}],
                }
            ],
            "generationConfig": {"temperature": 0.2},
        },
        timeout,
    )
    return response["candidates"][0]["content"]["parts"][0]["text"].strip()


def call_huggingface(prompt, model, timeout):
    api_key = os.environ.get("HF_TOKEN")
    if not api_key:
        raise RuntimeError("HF_TOKEN is not set.")
    hf_model = model or "mistralai/Mistral-7B-Instruct-v0.3"
    response = request_json(
        f"https://api-inference.huggingface.co/models/{hf_model}",
        {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        {
            "inputs": f"[INST] {DEFAULT_SYSTEM_PROMPT}\n\n{prompt} [/INST]",
            "parameters": {
                "max_new_tokens": 350,
                "temperature": 0.2,
                "return_full_text": False,
            },
        },
        timeout,
    )
    if isinstance(response, list) and response:
        return response[0].get("generated_text", "").strip()
    return json.dumps(response, ensure_ascii=False)


def call_llm(provider, prompt, model, timeout):
    if provider == "mock":
        raise RuntimeError("mock provider should be handled before call_llm.")
    if provider == "openrouter":
        return call_openrouter(prompt, model, timeout)
    if provider == "groq":
        return call_groq(prompt, model, timeout)
    if provider == "gemini":
        return call_gemini(prompt, model, timeout)
    if provider == "huggingface":
        return call_huggingface(prompt, model, timeout)
    raise ValueError(f"Unsupported provider: {provider}")


def make_markdown_report(results):
    lines = [
        "# ViT XAI LLM Explanation Report",
        "",
        "These explanations are generated from model predictions and XAI metadata. They are for research support only, not clinical diagnosis.",
        "",
    ]
    for item in results:
        sample = item["sample"]
        lines.extend(
            [
                f"## {sample['group']} - {sample['id']}",
                "",
                f"- Predicted label: **{label_name(sample['pred_label'])}**",
                f"- Ground truth: **{label_name(sample['true_label'])}**",
                f"- Cancer probability: **{float(sample['prob_cancer']):.4f}**",
                f"- Threshold: **{float(sample['threshold']):.2f}**",
                f"- Attention regions: `{sample['top_attention_regions']}`",
                "",
                item["explanation"],
                "",
            ]
        )
    return "\n".join(lines)


def main():
    args = parse_args()
    input_path = Path(args.input)
    output_dir = Path(args.output)
    samples = read_json(input_path)[: args.max_samples]
    results = []

    for index, sample in enumerate(samples, start=1):
        prompt = build_prompt(sample)
        if args.provider == "mock":
            explanation = mock_explanation(sample)
            status = "mock"
        else:
            explanation = call_llm(args.provider, prompt, args.model, args.timeout)
            status = "api"
            time.sleep(args.sleep)

        results.append(
            {
                "index": index,
                "provider": args.provider,
                "model": args.model,
                "status": status,
                "sample": sample,
                "prompt": prompt,
                "explanation": explanation,
            }
        )

    write_json(output_dir / "llm_explanations.json", results)
    write_text(output_dir / "llm_explanations.md", make_markdown_report(results))
    print(f"Saved LLM explanations to: {output_dir}")
    print(f"JSON: {output_dir / 'llm_explanations.json'}")
    print(f"Markdown: {output_dir / 'llm_explanations.md'}")


if __name__ == "__main__":
    main()
